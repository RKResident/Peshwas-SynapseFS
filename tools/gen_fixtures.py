#!/usr/bin/env python3
"""Synthetic checkpoint fixture generator for SynapseFS.

Why this tool exists
--------------------
SynapseFS is graded on *permutation-recovery accuracy* against checkpoint pairs
the team has never seen. There is exactly one way to measure that: apply a
permutation ourselves, withhold it from the alignment engine, and check whether
the engine reproduces it. That answer key cannot come from real checkpoints —
it has to be manufactured. This tool manufactures it.

The problem statement also asks that large synthetic fixtures stay out of commit
history and be regenerated by script instead; this is that script.

What it emits
-------------
For each model spec, five variants are written, each a directory containing
``model.safetensors`` + ``config.json``:

===================== ================================ ==========================
Variant               Construction                     Exercises
===================== ================================ ==========================
``base``              random init                      root-commit / full storage
``permuted``          ``base`` with a known pi applied  permutation recovery
``finetuned``         ``base`` + small dense noise      residual ratio
``permuted_finetuned``both of the above                 the hard case
``not_alignable``     independent random init          explicit non-alignability
===================== ================================ ==========================

``permuted`` and ``permuted_finetuned`` additionally carry ``ground_truth.json``
holding the permutations that were applied.

**The alignment engine must never read ``ground_truth.json``.** It is written for
tests and scoring only. If production code reads it, the accuracy metric becomes
meaningless. ``config.json`` is the only metadata the aligner is entitled to see,
and it is deliberately shaped like an ordinary HuggingFace config rather than
like a convenient description of our own internals.

Self-verification
-----------------
Applying a permutation correctly is itself fiddly: a row permutation on layer
``l`` must be matched by a column permutation on layer ``l+1``, biases and
normalisation parameters follow the row permutation, residual connections force
two layers to *share* a permutation group, and a conv-to-linear flatten permutes
*blocks* of columns rather than individual columns. Get any of that wrong and the
generator emits a model that is not functionally equivalent to its base — at
which point the aligner faithfully recovers nonsense and every test still passes.

So the generator checks itself: it pushes a fixed random input through the base
and through the permuted model and asserts the outputs match (§ :func:`verify_equivalence`).
That check doubles as a free correctness test of the exact permutation algebra
Track B has to reimplement.

Usage
-----
::

    python tools/gen_fixtures.py --arch mlp --size tiny  --out fixtures/mlp-tiny
    python tools/gen_fixtures.py --arch cnn --size small --out fixtures/cnn-small
    python tools/gen_fixtures.py --all --size tiny --out fixtures/
    python tools/gen_fixtures.py --arch mlp --size small --variants base finetuned
"""

