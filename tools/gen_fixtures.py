# A model is a flat name -> array mapping, mirroring the .safetensors key/value
# shape. Arrays are float32 while we are building and permuting them; they are
# narrowed to the storage dtype only at write time (see `to_storage_dtype`).
Tensors = dict[str, np.ndarray]

# A permutation group maps a group id (e.g. "g_hidden_0") to an int32 array `p`
# where `p[i]` is the index in the *source* model that lands at position `i` in
# the *permuted* model. This matches the `base_row_permutation` convention in
# docs/FileFormat.md section 4.2, deliberately: fixtures and production speak the
# same dialect.
PermGroups = dict[str, np.ndarray]

ALL_VARIANTS = (
    "base",
    "permuted",
    "finetuned",
    "permuted_finetuned",
    "not_alignable",
)


# --------------------------------------------------------------------------- #
# safetensors writer
# --------------------------------------------------------------------------- #
#
# We write .safetensors by hand rather than via safetensors.numpy.save_file for
# two reasons:
#
#   1. bf16 has no numpy dtype, so the numpy backend cannot emit it, and the PS
#      says checkpoints are evaluated in fp16/bf16. Writing the container
#      ourselves gets bf16 for free -- the payload is just uint16 bytes.
#   2. It forces us to encode the three conventions that silently break
#      byte-exactness downstream (see docs/FileFormat.md section 1.2), so they
#      are exercised from day one rather than discovered during integration.
#
# tests/test_fixtures.py asserts this writer round-trips through the real
# safetensors reader, which is what makes the shortcut safe.

_DTYPE_TO_ST: dict[str, str] = {
    "float16": "F16",
    "bfloat16": "BF16",
    "float32": "F32",
    "float64": "F64",
    "int64": "I64",
    "int32": "I32",
    "uint8": "U8",
    "bool": "BOOL",
}


def _st_dtype_name(arr: np.ndarray, declared: str | None) -> str:
    """Return the safetensors dtype string for `arr`.

    `declared` overrides inference and exists solely for bf16, which is carried
    in memory as uint16 because numpy has no bfloat16 dtype.
    """
    if declared is not None:
        return declared
    name = arr.dtype.name
    if name not in _DTYPE_TO_ST:
        raise ValueError(f"unsupported dtype for safetensors: {name}")
    return _DTYPE_TO_ST[name]


def save_safetensors(
    path: Path,
    tensors: Tensors,
    metadata: dict[str, str] | None = None,
    dtype_overrides: dict[str, str] | None = None,
) -> None:
    """Write `tensors` to `path` in .safetensors format.

    Reproduces the three layout conventions that a naive re-serialisation gets
    wrong, all verified against a file produced by safetensors 0.8.0:

    1. ``__metadata__`` is emitted first, before any tensor key.
    2. Tensor keys are sorted **alphabetically**, not by insertion order, and
       ``data_offsets`` follow that sorted order.
    3. The header JSON is padded with trailing spaces (0x20) so that
       ``8 + header_len`` is a multiple of 8, aligning the data region for mmap.

    Args:
        path: Destination file. Parent directories must already exist.
        tensors: Name -> array. Arrays must be C-contiguous.
        metadata: Optional string->string map stored under ``__metadata__``.
        dtype_overrides: Name -> safetensors dtype string, used to declare BF16
            for arrays carried as uint16.
    """
    dtype_overrides = dtype_overrides or {}
    header: dict[str, Any] = {}
    if metadata:
        header["__metadata__"] = {str(k): str(v) for k, v in metadata.items()}

    # Offsets are assigned in sorted-key order because that is the order the
    # payload is concatenated in below.
    offset = 0
    ordered: list[tuple[str, np.ndarray]] = []
    for name in sorted(tensors):
        arr = np.ascontiguousarray(tensors[name])
        nbytes = arr.nbytes
        header[name] = {
            "dtype": _st_dtype_name(arr, dtype_overrides.get(name)),
            "shape": list(arr.shape),
            "data_offsets": [offset, offset + nbytes],
        }
        ordered.append((name, arr))
        offset += nbytes

    blob = json.dumps(header, separators=(",", ":")).encode("utf-8")
    pad = (-(8 + len(blob))) % 8          # pad so the data region is 8-aligned
    blob += b" " * pad

    with open(path, "wb") as fh:
        fh.write(struct.pack("<Q", len(blob)))
        fh.write(blob)
        for _, arr in ordered:
            fh.write(arr.tobytes(order="C"))


def to_storage_dtype(arr: np.ndarray, dtype: str) -> tuple[np.ndarray, str | None]:
    """Narrow a float32 working array to the on-disk storage dtype.

    Returns:
        ``(array, declared_dtype)``. For bf16 the array is uint16 and
        `declared_dtype` is ``"BF16"``, because numpy cannot represent bf16 and
        safetensors must be told explicitly. For every other dtype
        `declared_dtype` is None and inference handles it.

    Note:
        bf16 conversion truncates rather than rounding to nearest even. That is
        fine for fixtures -- we only need *some* valid bf16 bit pattern, not the
        nearest one -- and it keeps the conversion a pure bit operation.
    """
    if dtype == "bf16":
        u32 = np.ascontiguousarray(arr, dtype=np.float32).view(np.uint32)
        return (u32 >> 16).astype(np.uint16), "BF16"
    if dtype == "fp16":
        return arr.astype(np.float16), None
    if dtype == "fp32":
        return arr.astype(np.float32), None
    raise ValueError(f"unknown storage dtype: {dtype!r}")


# --------------------------------------------------------------------------- #
# Model specs
# --------------------------------------------------------------------------- #


@dataclass(frozen=True)
class MLPSpec:
    """A plain feed-forward stack: Linear -> LayerNorm -> ReLU, repeated.

    Attributes:
        in_dim: Input feature count. Pinned -- never permuted.
        hidden: Width of every hidden layer.
        depth: Number of Linear layers *including* the output layer, so there
            are ``depth - 1`` permutable groups.
        out_dim: Output feature count. Pinned -- never permuted.
    """

    in_dim: int
    hidden: int
    depth: int
    out_dim: int

    @property
    def param_count(self) -> int:
        """Approximate parameter count, for size reporting."""
        n = self.in_dim * self.hidden + self.hidden
        n += (self.depth - 2) * (self.hidden * self.hidden + self.hidden)
        n += self.hidden * self.out_dim + self.out_dim
        n += (self.depth - 1) * 2 * self.hidden          # LayerNorm affine
        return n


@dataclass(frozen=True)
class CNNSpec:
    """A ResNet-style stack: stem conv, N residual basic blocks, linear head.

    Channel width is constant throughout and there is no downsampling. That is
    deliberate: it keeps every residual skip an identity, which forces the block
    input and block output to *share* a permutation group. Group tying is the
    part of the topology resolver most likely to be wrong, so the fixtures
    should exercise it.

    Attributes:
        in_ch: Input image channels. Pinned.
        channels: Constant channel width for the stem and every block.
        blocks: Number of residual basic blocks.
        spatial: Input height and width (square).
        num_classes: Head output width. Pinned.
        head: ``"flatten"`` or ``"pool"``. ``"flatten"`` makes the head's input
            ``channels * spatial * spatial``, so a channel permutation moves
            *blocks* of ``spatial**2`` columns -- the conv-to-linear flatten
            case. ``"pool"`` global-average-pools first, giving block size 1.
            Default is ``"flatten"`` precisely because it is the harder path.
    """

    in_ch: int
    channels: int
    blocks: int
    spatial: int
    num_classes: int
    head: str = "flatten"

    @property
    def block_size(self) -> int:
        """Columns per channel in the head weight -- the `col_block_size`."""
        return self.spatial * self.spatial if self.head == "flatten" else 1

    @property
    def param_count(self) -> int:
        """Approximate parameter count, for size reporting."""
        c = self.channels
        n = c * self.in_ch * 9 + 4 * c
        n += self.blocks * (2 * c * c * 9 + 8 * c)
        n += self.num_classes * c * self.block_size + self.num_classes
        return n


