@dataclass
class Variant:
    """One generated model directory, ready to be written."""

    name: str
    tensors: Tensors
    groups: PermGroups | None = None
    provenance: dict[str, Any] = field(default_factory=dict)


def _write_variant(
    out_dir: Path, v: Variant, config: dict[str, Any], dtype: str
) -> dict[str, Any]:
    """Write one variant directory and return a manifest entry describing it."""
    d = out_dir / v.name
    d.mkdir(parents=True, exist_ok=True)

    storage: Tensors = {}
    overrides: dict[str, str] = {}
    for k, arr in v.tensors.items():
        conv, declared = to_storage_dtype(arr, dtype)
        storage[k] = conv
        if declared:
            overrides[k] = declared

    model_path = d / "model.safetensors"
    save_safetensors(
        model_path,
        storage,
        metadata={"format": "pt", "synapsefs_variant": v.name},
        dtype_overrides=overrides,
    )
    (d / "config.json").write_text(json.dumps(config, indent=2) + "\n")

    if v.groups is not None:
        # Written to its OWN file, never into config.json. The aligner reads
        # config.json; only tests may read this.
        (d / "ground_truth.json").write_text(
            json.dumps(
                {
                    "_warning": (
                        "Answer key. Tests and scoring only. "
                        "The alignment engine must never read this file."
                    ),
                    "permutations": {k: p.tolist() for k, p in v.groups.items()},
                    **v.provenance,
                },
                indent=2,
            )
            + "\n"
        )

    return {
        "variant": v.name,
        "path": str(d.relative_to(out_dir.parent)),
        "bytes": model_path.stat().st_size,
        "tensors": len(storage),
        "has_ground_truth": v.groups is not None,
        **v.provenance,
    }


def generate(
    arch: str,
    spec: MLPSpec | CNNSpec,
    out_dir: Path,
    seed: int,
    dtype: str,
    variants: Iterable[str],
    rel_scale: float,
    verify: bool = True,
) -> dict[str, Any]:
    """Generate one complete fixture set.

    Args:
        arch: ``"mlp"`` or ``"cnn"``.
        spec: The matching spec dataclass.
        out_dir: Directory to create; one subdirectory per variant.
        seed: Master seed. Everything downstream derives from it, so the whole
            set is reproducible from ``(arch, spec, seed)`` alone -- which is
            what lets us keep fixtures out of git.
        dtype: ``"fp16"``, ``"bf16"`` or ``"fp32"``.
        variants: Subset of :data:`ALL_VARIANTS` to emit.
        rel_scale: Fine-tuning noise scale, relative to each tensor's own std.
        verify: Run the functional-equivalence check on permuted variants.

    Returns:
        A manifest dict, also written to ``MANIFEST.json``.
    """
    wanted = list(variants)
    rng = np.random.default_rng(seed)

    if arch == "mlp":
        assert isinstance(spec, MLPSpec)
        base = build_mlp(spec, rng)
        config = mlp_config(spec)
        permute = lambda t, r: permute_mlp(spec, t, r)          # noqa: E731
        fwd = lambda t, x: forward_mlp(spec, t, x)              # noqa: E731
        probe = rng.normal(size=(4, spec.in_dim)).astype(np.float32)
        reinit = lambda r: build_mlp(spec, r)                   # noqa: E731
    elif arch == "cnn":
        assert isinstance(spec, CNNSpec)
        base = build_cnn(spec, rng)
        config = cnn_config(spec)
        permute = lambda t, r: permute_cnn(spec, t, r)          # noqa: E731
        fwd = lambda t, x: forward_cnn(spec, t, x)              # noqa: E731
        probe = rng.normal(size=(2, spec.in_ch, spec.spatial, spec.spatial)).astype(np.float32)
        reinit = lambda r: build_cnn(spec, r)                   # noqa: E731
    else:
        raise ValueError(f"unknown arch: {arch!r}")

    built: list[Variant] = []
    checks: dict[str, float] = {}

    if "base" in wanted:
        built.append(Variant("base", base, provenance={"derived_from": None}))

    perm_t: Tensors | None = None
    perm_g: PermGroups | None = None
    if {"permuted", "permuted_finetuned"} & set(wanted):
        perm_t, perm_g = permute(base, np.random.default_rng(seed + 1))
        if verify:
            checks["permuted"] = verify_equivalence(fwd, base, perm_t, probe)

    if "permuted" in wanted:
        built.append(
            Variant("permuted", perm_t, perm_g, {"derived_from": "base", "permuted": True})
        )

    if "finetuned" in wanted:
        built.append(
            Variant(
                "finetuned",
                finetune(base, np.random.default_rng(seed + 2), rel_scale),
                provenance={"derived_from": "base", "finetune_rel_scale": rel_scale},
            )
        )

    if "permuted_finetuned" in wanted:
        built.append(
            Variant(
                "permuted_finetuned",
                finetune(perm_t, np.random.default_rng(seed + 3), rel_scale),
                perm_g,
                {
                    "derived_from": "base",
                    "permuted": True,
                    "finetune_rel_scale": rel_scale,
                },
            )
        )

    if "not_alignable" in wanted:
        # Same architecture, independently initialised. Weight matching will
        # still *find* a permutation -- it always does -- but the residual will
        # barely improve over the unaligned baseline. That gap is the signal the
        # engine must detect and report, per the PS requirement to recognise
        # non-alignable pairs rather than force a low-confidence match.
        built.append(
            Variant(
                "not_alignable",
                reinit(np.random.default_rng(seed + 9999)),
                provenance={"derived_from": None, "independently_initialised": True},
            )
        )

    out_dir.mkdir(parents=True, exist_ok=True)
    entries = [_write_variant(out_dir, v, config, dtype) for v in built]

    manifest = {
        "arch": arch,
        "spec": spec.__dict__,
        "seed": seed,
        "dtype": dtype,
        "approx_params": spec.param_count,
        "regenerate_with": (
            f"python tools/gen_fixtures.py --arch {arch} --seed {seed} "
            f"--dtype {dtype} --out {out_dir}"
        ),
        "equivalence_max_rel_deviation": checks,
        "variants": entries,
    }
    if isinstance(spec, CNNSpec):
        manifest["col_block_size"] = spec.block_size

    (out_dir / "MANIFEST.json").write_text(json.dumps(manifest, indent=2) + "\n")
    return manifest


