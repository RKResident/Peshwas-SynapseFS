def _human(n: int) -> str:
    """Format a byte count for progress output."""
    for unit in ("B", "KiB", "MiB", "GiB"):
        if n < 1024 or unit == "GiB":
            return f"{n:.1f} {unit}" if unit != "B" else f"{n} B"
        n /= 1024.0
    return f"{n:.1f} GiB"


def _check_disk(out: Path, spec: MLPSpec | CNNSpec, n_variants: int, dtype: str) -> None:
    """Warn before filling a nearly-full disk.

    The development machine has ~24 GB free on a 93%-full drive (docs/PLAN.md
    section 0), so a careless ``--size large --all`` is a real hazard.
    """
    per_elem = 4 if dtype == "fp32" else 2
    need = spec.param_count * per_elem * n_variants
    free = shutil.disk_usage(out.parent if out.parent.exists() else Path(".")).free
    print(f"  estimated output: {_human(need)}   free: {_human(free)}", file=sys.stderr)
    if need > free * 0.5:
        print(
            f"  WARNING: this would use more than half the free space on this "
            f"disk. Consider a smaller --size or fewer --variants.",
            file=sys.stderr,
        )


def main(argv: list[str] | None = None) -> int:
    """Entry point. Returns a process exit code."""
    ap = argparse.ArgumentParser(
        description="Generate synthetic SynapseFS checkpoint fixtures.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__.split("Usage\n-----\n")[-1],
    )
    ap.add_argument("--arch", choices=("mlp", "cnn"), help="architecture to generate")
    ap.add_argument("--all", action="store_true", help="generate both architectures")
    ap.add_argument("--size", choices=tuple(SIZE_PRESETS), default="tiny")
    ap.add_argument("--out", type=Path, required=True, help="output directory")
    ap.add_argument("--seed", type=int, default=0, help="master seed (default: 0)")
    ap.add_argument("--dtype", choices=("fp16", "bf16", "fp32"), default="fp16")
    ap.add_argument(
        "--variants",
        nargs="+",
        choices=ALL_VARIANTS,
        default=list(ALL_VARIANTS),
        help="subset of variants to emit (default: all five)",
    )
    ap.add_argument(
        "--finetune-scale",
        type=float,
        default=1e-3,
        help="fine-tuning noise, relative to each tensor's std (default: 1e-3)",
    )
    ap.add_argument(
        "--no-verify",
        action="store_true",
        help="skip the functional-equivalence check (not recommended)",
    )
    args = ap.parse_args(argv)

    if not args.arch and not args.all:
        ap.error("specify --arch {mlp,cnn} or --all")

    archs = ("mlp", "cnn") if args.all else (args.arch,)
    rc = 0

    for arch in archs:
        spec = SIZE_PRESETS[args.size][arch]
        out = args.out / f"{arch}-{args.size}" if args.all else args.out
        print(f"\n{arch} / {args.size}  (~{spec.param_count / 1e6:.1f}M params)", file=sys.stderr)
        _check_disk(out, spec, len(args.variants), args.dtype)

        try:
            m = generate(
                arch=arch,
                spec=spec,
                out_dir=out,
                seed=args.seed,
                dtype=args.dtype,
                variants=args.variants,
                rel_scale=args.finetune_scale,
                verify=not args.no_verify,
            )
        except AssertionError as e:
            print(f"  FAILED: {e}", file=sys.stderr)
            rc = 1
            continue

        for dev_name, dev in m["equivalence_max_rel_deviation"].items():
            print(f"  equivalence check [{dev_name}]: max rel dev {dev:.2e}  OK", file=sys.stderr)
        for e in m["variants"]:
            gt = "  + ground_truth.json" if e["has_ground_truth"] else ""
            print(f"  {e['variant']:<20} {_human(e['bytes']):>10}{gt}", file=sys.stderr)
        print(f"  manifest: {out / 'MANIFEST.json'}", file=sys.stderr)

    return rc


if __name__ == "__main__":
    raise SystemExit(main())
