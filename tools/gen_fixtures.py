def mlp_config(spec: MLPSpec) -> dict[str, Any]:
    """Emit a HuggingFace-shaped config for an MLP.

    Intentionally describes the *architecture*, not our permutation groups. The
    topology resolver has to derive groups from this, which is the job it will
    have to do against the real evaluation fixtures.
    """
    return {
        "model_type": "synapse_mlp",
        "architectures": ["SynapseMLPForClassification"],
        "input_size": spec.in_dim,
        "hidden_size": spec.hidden,
        "num_hidden_layers": spec.depth,
        "num_labels": spec.out_dim,
        "hidden_act": "relu",
        "norm_type": "layer_norm",
        "layer_norm_eps": 1e-5,
        "torch_dtype": "float16",
    }


def cnn_config(spec: CNNSpec) -> dict[str, Any]:
    """Emit a HuggingFace-shaped config for a ResNet-style CNN."""
    return {
        "model_type": "synapse_resnet",
        "architectures": ["SynapseResNetForImageClassification"],
        "num_channels": spec.in_ch,
        "hidden_sizes": [spec.channels] * spec.blocks,
        "depths": [spec.blocks],
        "num_blocks": spec.blocks,
        "kernel_size": 3,
        "stride": 1,
        "padding": 1,
        "image_size": spec.spatial,
        "num_labels": spec.num_classes,
        "hidden_act": "relu",
        "norm_type": "batch_norm",
        "pooling": spec.head,
        "torch_dtype": "float16",
    }


