# --------------------------------------------------------------------------- #
# Model construction
# --------------------------------------------------------------------------- #


def _kaiming(rng: np.random.Generator, *shape: int, fan_in: int) -> np.ndarray:
    """He-normal init. Realistic magnitudes matter for the residual-ratio metric."""
    return rng.normal(0.0, math.sqrt(2.0 / fan_in), size=shape).astype(np.float32)


def build_mlp(spec: MLPSpec, rng: np.random.Generator) -> Tensors:
    """Construct a randomly initialised MLP.

    Tensor naming mirrors a typical PyTorch ``state_dict`` so the topology
    parser is exercised against realistic key strings rather than a convenient
    private scheme.
    """
    t: Tensors = {}
    dims = [spec.in_dim] + [spec.hidden] * (spec.depth - 1) + [spec.out_dim]
    for i in range(spec.depth):
        fan_in, fan_out = dims[i], dims[i + 1]
        t[f"layers.{i}.weight"] = _kaiming(rng, fan_out, fan_in, fan_in=fan_in)
        t[f"layers.{i}.bias"] = np.zeros(fan_out, dtype=np.float32)
        if i < spec.depth - 1:                       # no norm on the output layer
            t[f"layers.{i}.norm.weight"] = np.ones(fan_out, dtype=np.float32)
            t[f"layers.{i}.norm.bias"] = np.zeros(fan_out, dtype=np.float32)
    return t


def build_cnn(spec: CNNSpec, rng: np.random.Generator) -> Tensors:
    """Construct a randomly initialised ResNet-style CNN.

    BatchNorm running statistics are randomised rather than left at their
    ``(0, 1)`` defaults. If they stayed at defaults they would be identical
    across every variant and would dedup perfectly, quietly flattering the
    residual-ratio metric.
    """
    t: Tensors = {}
    c = spec.channels

    t["stem.weight"] = _kaiming(rng, c, spec.in_ch, 3, 3, fan_in=spec.in_ch * 9)
    _add_bn(t, "stem.bn", c, rng)

    for b in range(spec.blocks):
        t[f"blocks.{b}.conv1.weight"] = _kaiming(rng, c, c, 3, 3, fan_in=c * 9)
        _add_bn(t, f"blocks.{b}.bn1", c, rng)
        t[f"blocks.{b}.conv2.weight"] = _kaiming(rng, c, c, 3, 3, fan_in=c * 9)
        _add_bn(t, f"blocks.{b}.bn2", c, rng)

    head_in = c * spec.block_size
    t["head.weight"] = _kaiming(rng, spec.num_classes, head_in, fan_in=head_in)
    t["head.bias"] = np.zeros(spec.num_classes, dtype=np.float32)
    return t


def _add_bn(t: Tensors, prefix: str, c: int, rng: np.random.Generator) -> None:
    """Add the four BatchNorm tensors under `prefix`, all on the channel axis."""
    t[f"{prefix}.weight"] = rng.uniform(0.8, 1.2, size=c).astype(np.float32)
    t[f"{prefix}.bias"] = rng.normal(0.0, 0.05, size=c).astype(np.float32)
    t[f"{prefix}.running_mean"] = rng.normal(0.0, 0.1, size=c).astype(np.float32)
    t[f"{prefix}.running_var"] = rng.uniform(0.5, 1.5, size=c).astype(np.float32)


# --------------------------------------------------------------------------- #
# Permutation
# --------------------------------------------------------------------------- #


def _permute_rows(w: np.ndarray, p: np.ndarray) -> np.ndarray:
    """Permute axis 0. ``out[i] == w[p[i]]``."""
    return w[p]


def _permute_cols(w: np.ndarray, p: np.ndarray, block: int = 1) -> np.ndarray:
    """Permute axis 1 in contiguous blocks of `block` columns.

    ``block == 1`` is the ordinary linear case. ``block > 1`` is the
    conv-to-linear flatten case: a flattened ``[out, in_ch * H * W]`` weight has
    its columns grouped by input channel, so permuting channel ``c`` to position
    ``i`` moves the whole span ``[c*block, (c+1)*block)``.

    This is the single most error-prone line in the file. It is also invisible
    under an identity permutation, which is why the CNN fixture must be tested
    with a non-identity one.
    """
    if block == 1:
        return w[:, p]
    idx = (p[:, None] * block + np.arange(block)[None, :]).ravel()
    return w[:, idx]


def permute_mlp(spec: MLPSpec, t: Tensors, rng: np.random.Generator) -> tuple[Tensors, PermGroups]:
    """Apply a random permutation to every hidden layer of an MLP.

    The input and output layers are pinned: permuting them would change the
    function the network computes as seen from outside, which is exactly what
    permutation symmetry does *not* do.

    Returns:
        ``(permuted_tensors, groups)`` where `groups` maps ``"g_hidden_{i}"`` to
        the permutation applied to layer ``i``'s output.
    """
    groups: PermGroups = {
        f"g_hidden_{i}": rng.permutation(spec.hidden).astype(np.int32)
        for i in range(spec.depth - 1)
    }
    ident_in = np.arange(spec.in_dim, dtype=np.int32)
    out: Tensors = {}

    for i in range(spec.depth):
        p_in = ident_in if i == 0 else groups[f"g_hidden_{i - 1}"]
        p_out = groups.get(f"g_hidden_{i}")           # None on the output layer

        w = t[f"layers.{i}.weight"]
        w = _permute_cols(w, p_in)
        if p_out is not None:
            w = _permute_rows(w, p_out)
        out[f"layers.{i}.weight"] = w

        b = t[f"layers.{i}.bias"]
        out[f"layers.{i}.bias"] = b if p_out is None else b[p_out]

        if p_out is not None:
            for suf in ("norm.weight", "norm.bias"):
                out[f"layers.{i}.{suf}"] = t[f"layers.{i}.{suf}"][p_out]

    return out, groups


def permute_cnn(spec: CNNSpec, t: Tensors, rng: np.random.Generator) -> tuple[Tensors, PermGroups]:
    """Apply a random permutation to a ResNet-style CNN.

    Two kinds of group, and the distinction is the point of this fixture:

    * ``g_skip`` -- the residual-path width. Because every skip connection is an
      identity, the stem output, every ``conv2`` output, and the head's input
      channels must **all** use the same permutation. A resolver that treats
      each layer independently will produce a model that is not functionally
      equivalent, and :func:`verify_equivalence` will catch it.
    * ``g_block_{b}`` -- block ``b``'s internal width, between ``conv1`` and
      ``conv2``. Free to permute independently.
    """
    groups: PermGroups = {"g_skip": rng.permutation(spec.channels).astype(np.int32)}
    for b in range(spec.blocks):
        groups[f"g_block_{b}"] = rng.permutation(spec.channels).astype(np.int32)

    p_skip = groups["g_skip"]
    ident_in = np.arange(spec.in_ch, dtype=np.int32)
    out: Tensors = {}

    # Stem: rows on the skip group, columns pinned to the input channels.
    out["stem.weight"] = t["stem.weight"][np.ix_(p_skip, ident_in)]
    _permute_bn(out, t, "stem.bn", p_skip)

    for b in range(spec.blocks):
        p_int = groups[f"g_block_{b}"]
        # conv1: rows -> internal group, cols -> skip group (block input).
        out[f"blocks.{b}.conv1.weight"] = t[f"blocks.{b}.conv1.weight"][np.ix_(p_int, p_skip)]
        _permute_bn(out, t, f"blocks.{b}.bn1", p_int)
        # conv2: rows -> skip group (tied to the residual), cols -> internal.
        out[f"blocks.{b}.conv2.weight"] = t[f"blocks.{b}.conv2.weight"][np.ix_(p_skip, p_int)]
        _permute_bn(out, t, f"blocks.{b}.bn2", p_skip)

    # Head: rows pinned (class logits), columns follow the skip group in blocks.
    out["head.weight"] = _permute_cols(t["head.weight"], p_skip, spec.block_size)
    out["head.bias"] = t["head.bias"].copy()
    return out, groups


def _permute_bn(out: Tensors, t: Tensors, prefix: str, p: np.ndarray) -> None:
    """Apply `p` to all four BatchNorm tensors under `prefix`."""
    for suf in ("weight", "bias", "running_mean", "running_var"):
        out[f"{prefix}.{suf}"] = t[f"{prefix}.{suf}"][p]


# --------------------------------------------------------------------------- #
# Perturbation
# --------------------------------------------------------------------------- #


def finetune(t: Tensors, rng: np.random.Generator, rel_scale: float = 1e-3) -> Tensors:
    """Perturb every tensor to imitate a fine-tuning step.

    The noise is scaled *relative to each tensor's own standard deviation*, so a
    weight matrix and a BatchNorm gamma both move by a comparable fraction of
    their natural magnitude. A single absolute scale would leave small-magnitude
    tensors untouched and make the residual look better than it should.

    The perturbation is dense -- every element moves. That is the realistic
    fine-tuning case and it is why chunk-level deduplication buys little on the
    residual itself (see docs/FORMAT.md section 1.3).

    Args:
        rel_scale: Noise standard deviation as a fraction of each tensor's own.
            ``1e-3`` is a light step; raise it to model a longer run.
    """
    out: Tensors = {}
    for k, v in t.items():
        sigma = float(v.std()) or 1.0
        out[k] = (v + rng.normal(0.0, sigma * rel_scale, size=v.shape)).astype(np.float32)
    return out


# --------------------------------------------------------------------------- #
# Forward passes (self-verification only)
# --------------------------------------------------------------------------- #
#
# These exist so the generator can prove it permuted correctly. They are not
# performance-sensitive and are not used by anything in synapsefs/.


def _layernorm(x: np.ndarray, g: np.ndarray, b: np.ndarray, eps: float = 1e-5) -> np.ndarray:
    """LayerNorm over the last axis.

    Permutation-equivariant, which is why permuting a hidden layer is safe:
    mean and variance are taken over *all* features, so reordering them leaves
    both statistics unchanged.
    """
    mu = x.mean(axis=-1, keepdims=True)
    var = x.var(axis=-1, keepdims=True)
    return (x - mu) / np.sqrt(var + eps) * g + b


def forward_mlp(spec: MLPSpec, t: Tensors, x: np.ndarray) -> np.ndarray:
    """Run `x` (shape ``[N, in_dim]``) through the MLP in float32."""
    h = x.astype(np.float32)
    for i in range(spec.depth):
        h = h @ t[f"layers.{i}.weight"].T.astype(np.float32) + t[f"layers.{i}.bias"]
        if i < spec.depth - 1:
            h = _layernorm(h, t[f"layers.{i}.norm.weight"], t[f"layers.{i}.norm.bias"])
            h = np.maximum(h, 0.0)
    return h


def _conv2d(x: np.ndarray, w: np.ndarray, pad: int = 1) -> np.ndarray:
    """Stride-1 2D convolution, NCHW, accumulating one kernel offset at a time."""
    n, _, hh, ww = x.shape
    o, _, kh, kw = w.shape
    xp = np.pad(x, ((0, 0), (0, 0), (pad, pad), (pad, pad)))
    out = np.zeros((n, o, hh, ww), dtype=np.float32)
    for i in range(kh):
        for j in range(kw):
            out += np.einsum("nchw,oc->nohw", xp[:, :, i : i + hh, j : j + ww], w[:, :, i, j])
    return out


def _batchnorm(x: np.ndarray, t: Tensors, prefix: str, eps: float = 1e-5) -> np.ndarray:
    """Inference-mode BatchNorm using the stored running statistics."""
    m = t[f"{prefix}.running_mean"][None, :, None, None]
    v = t[f"{prefix}.running_var"][None, :, None, None]
    g = t[f"{prefix}.weight"][None, :, None, None]
    b = t[f"{prefix}.bias"][None, :, None, None]
    return (x - m) / np.sqrt(v + eps) * g + b


def forward_cnn(spec: CNNSpec, t: Tensors, x: np.ndarray) -> np.ndarray:
    """Run `x` (shape ``[N, in_ch, S, S]``) through the CNN in float32."""
    h = np.maximum(_batchnorm(_conv2d(x, t["stem.weight"]), t, "stem.bn"), 0.0)
    for b in range(spec.blocks):
        r = h
        h = np.maximum(_batchnorm(_conv2d(h, t[f"blocks.{b}.conv1.weight"]), t, f"blocks.{b}.bn1"), 0.0)
        h = _batchnorm(_conv2d(h, t[f"blocks.{b}.conv2.weight"]), t, f"blocks.{b}.bn2")
        h = np.maximum(h + r, 0.0)                    # identity skip -> tied group
    h = h.reshape(h.shape[0], -1) if spec.head == "flatten" else h.mean(axis=(2, 3))
    return h @ t["head.weight"].T + t["head.bias"]


def verify_equivalence(
    forward: Callable[[Tensors, np.ndarray], np.ndarray],
    base: Tensors,
    permuted: Tensors,
    x: np.ndarray,
    tol: float = 1e-3,
) -> float:
    """Assert that permuting did not change the function the network computes.

    This is the load-bearing check in the whole tool. A permutation is only a
    *symmetry* if the model's outputs are unchanged; if they are not, the
    fixture is wrong and every downstream accuracy number computed against it is
    meaningless.

    Args:
        tol: Maximum tolerated relative deviation. Float32 accumulation over a
            deep stack drifts slightly even for an exact permutation, because
            summation order changes -- so this is deliberately not exact
            equality. Byte-exactness is a property of the *storage* layer, not
            of this arithmetic.

    Returns:
        The observed maximum relative deviation, for reporting.

    Raises:
        AssertionError: If deviation exceeds `tol`, meaning the permutation
            algebra above is wrong.
    """
    a, b = forward(base, x), forward(permuted, x)
    denom = max(float(np.abs(a).max()), 1e-8)
    dev = float(np.abs(a - b).max() / denom)
    assert dev <= tol, (
        f"permuted model is NOT functionally equivalent to its base "
        f"(max relative deviation {dev:.3e} > tol {tol:.3e}). "
        f"The permutation algebra is wrong -- fix it before trusting any fixture."
    )
    return dev


